// ── Public API ───────────────────────────────────────────────────────────────

export async function generate(
  ctoSource: string,
  target: TargetLanguage,
): Promise<GenerationResult> {
  try {
    const output = await generateLive(ctoSource, target);
    return { output, isLive: true };
  } catch (liveError) {
    // Fall back to static output for the NDA example
    const fallback = STATIC[target];
    return {
      output: fallback,
      isLive: false,
      error:
        liveError instanceof Error ? liveError.message : String(liveError),
    };
  }
}
