/**
 * Concerto code generation wrapper.
 *
 * Attempts to use the real @accordproject/concerto-core + concerto-codegen
 * packages for live generation. Falls back to pre-generated static samples
 * if bundling or parsing fails, so the playground always shows meaningful output.
 */

export type TargetLanguage =
  | "typescript"
  | "jsonschema"
  | "python"
  | "java"
  | "go"
  | "openapi";

export interface GenerationResult {
  output: string;
  isLive: boolean; // true = generated from the actual model; false = static fallback
  error?: string;
}

// ── Live generation ──────────────────────────────────────────────────────────

async function generateLive(
  ctoSource: string,
  target: TargetLanguage,
): Promise<string> {
  // Dynamic imports so Vite can tree-shake if bundling fails
  const { ModelManager } = await import("@accordproject/concerto-core");
  const { CodeGen } = await import("@accordproject/concerto-codegen");
  const { InMemoryWriter } = await import("@accordproject/concerto-util");

  const modelManager = new ModelManager();
  modelManager.addCTOModel(ctoSource, "input.cto", true);
  await modelManager.updateExternalModels();

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const visitorMap: Partial<Record<TargetLanguage, new () => any>> = {
    typescript: CodeGen.TypescriptVisitor,
    jsonschema: CodeGen.JSONSchemaVisitor,
    java: CodeGen.JavaVisitor,
    go: CodeGen.GoLangVisitor,
    openapi: CodeGen.OpenApiVisitor,
  };

  const VisitorClass = visitorMap[target];
  if (!VisitorClass) throw new Error(`No live visitor for target: ${target}`);
  const writer = new InMemoryWriter();
  const visitor = new VisitorClass();
  visitor.visit(modelManager, { fileWriter: writer });

  const files: Map<string, string> = writer.getFilesInMemory();
  const parts: string[] = [];
  for (const [fileName, content] of files) {
    parts.push(`// ${fileName}\n${content}`);
  }
  return parts.join("\n\n");
}

